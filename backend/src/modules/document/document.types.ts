import type { PreflightRejectionReason } from '@core/pdf';

/** One uploaded file that has been signed. Every record here is created only after signing succeeds. */
export interface IDocumentVersionRecord {
    versionId: string;
    documentId: string;
    versionNumber: number;
    ownerId: string;
    mediaType: string;
    sizeBytes: number;
    sha256: string;
    /** The profile actually signed under. */
    profile: string;
    /** True when the handler offered content evidence (e.g. text) but this upload didn't get it. */
    profileDowngraded: boolean;
    /** Required and user-facing when profileDowngraded is true. Never silently downgrade. */
    downgradeReason?: string;
    proofId: string;
    /** False if the original bytes could not be stored or are no longer available. Verification never depends on this. */
    storageAvailable: boolean;
    storagePath?: string;
    createdAt: Date;
}

export interface INewDocumentVersionInput {
    /** Pre-generated by the caller so it matches the versionId already used in the proof and segment index. */
    versionId: string;
    documentId: string;
    ownerId: string;
    mediaType: string;
    sizeBytes: number;
    sha256: string;
    profile: string;
    profileDowngraded: boolean;
    downgradeReason?: string;
    proofId: string;
    storageAvailable: boolean;
    storagePath?: string;
}

export interface IDocumentRecord {
    documentId: string;
    ownerId: string;
    displayName: string;
    latestVersionNumber: number;
    latestVersionId: string;
    createdAt: Date;
    updatedAt: Date;
}

export interface INewDocumentInput {
    ownerId: string;
    displayName: string;
}

/**
 * What the upload endpoint returns to the caller: the result plus an explicit notice, never a silent
 * downgrade. `reason` is a plain string (not PreflightRejectionReason) because future, non-PDF handlers
 * may introduce their own rejection reasons that this module does not need to know about in advance.
 */
export interface IUploadRejection {
    accepted: false;
    reason: PreflightRejectionReason | 'unsupported-media-type' | (string & {});
    detail?: string;
}